#include <stdio.h>
int main() {
    //字符常量
    //字符常量是用单引号括起来的单个字符，例如 'a'、'1'、'%' 等。它们在 C 语言中表示一个字符类型的值，通常用于表示字符数据。
    //字符常量的类型是 int，而不是 char。这是因为在 C 语言中，字符常量在表达式中会被提升为 int 类型。
    //定义一个字符常量
    char ch = 'A';
    printf("字符常量: %c\n", ch);

    //整数常量
    //整数常量是用数字表示的整数值，例如 10、-5、0 等。它们在 C 语言中表示一个整数类型的值，通常用于表示整数数据。
    //整数常量的类型可以是 int、long、unsigned int 等，具体取决于常量的大小和符号。
    //定义一个整数常量
    int num = 100;
    printf("整数常量: %d\n", num);
    
    //浮点常量
    //浮点常量是用数字表示的带有小数点的数值，例如 3.14、-0.5、2.0e10 等。它们在 C 语言中表示一个浮点类型的值，通常用于表示小数数据。
    //浮点常量的类型可以是 float、double、long double 等，具体取决于常量的大小和精度。
    //定义一个浮点常量
    float pi = 3.14f;
    printf("浮点常量: %f\n", pi);

    //字符串常量
    //字符串常量是用双引号括起来的一系列字符，例如 "Hello, World!"、"C Programming" 等。它们在 C 语言中表示一个字符串类型的值，通常用于表示文本数据。
    //字符串常量的类型是 char 数组，实际上是一个以 null 字符 '\0' 结尾的字符数组。
    //定义一个字符串常量   
    char st[] = "Hello, World!";
    printf("字符串常量: %s\n", st);

    return 0;
}